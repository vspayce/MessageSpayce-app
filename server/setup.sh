#!/usr/bin/env bash
# Sculpin Server setup — a private Matrix server with an iMessage bridge.
#
#   curl -fsSLO https://raw.githubusercontent.com/vspayce/MessageSpayce-app/sculpin/server/setup.sh
#   bash setup.sh
#
# What it builds (all in Docker, in ~/sculpin-server):
#   - Synapse (Matrix server) + Postgres
#   - iMessage bridge (RustPush, ghcr.io/jasonlaguidice/imessage)
# Reachable ONLY through your Tailscale network (HTTPS via `tailscale serve`).
# No federation, no public ports. Bridge <-> apps traffic is end-to-end encrypted.
#
# Safe to re-run: finished steps are skipped.

set -euo pipefail

DIR="${SCULPIN_DIR:-$HOME/sculpin-server}"
TS_HOSTNAME="${SCULPIN_TS_HOSTNAME:-matrix}"
BRIDGE_IMAGE="ghcr.io/jasonlaguidice/imessage:latest"
SYNAPSE_IMAGE="matrixdotorg/synapse:latest"

bold() { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die()  { printf '\n\033[31mError:\033[0m %s\n' "$*" >&2; exit 1; }
ask()  { local p="$1" d="${2:-}" a; read -r -p "  $p${d:+ [$d]}: " a </dev/tty; echo "${a:-$d}"; }

# ── 0. Checks ────────────────────────────────────────────────────────────────
bold "Sculpin Server setup"
[ "$(uname -s)" = "Linux" ] || die "Run this on the Linux machine that will be the server."
[ "$(uname -m)" = "x86_64" ] || die "The iMessage bridge image is x86_64 (amd64) only. This machine is $(uname -m)."
command -v python3 >/dev/null || die "python3 is required (sudo apt install python3)."
command -v curl >/dev/null || die "curl is required (sudo apt install curl)."
sudo -v || die "This script needs sudo."
mkdir -p "$DIR"
cd "$DIR"
ok "Working in $DIR"

# ── 1. Docker ────────────────────────────────────────────────────────────────
bold "1/7  Docker"
if ! command -v docker >/dev/null; then
  curl -fsSL https://get.docker.com | sudo sh
  ok "Docker installed"
else
  ok "Docker already installed"
fi
sudo docker compose version >/dev/null 2>&1 || die "Docker Compose plugin missing (sudo apt install docker-compose-plugin)."
DC="sudo docker compose -f $DIR/compose.yml --env-file $DIR/.env"

# ── 2. Tailscale ─────────────────────────────────────────────────────────────
bold "2/7  Tailscale"
if ! command -v tailscale >/dev/null; then
  curl -fsSL https://tailscale.com/install.sh | sh
  ok "Tailscale installed"
fi
if ! sudo tailscale status >/dev/null 2>&1; then
  echo "  Sign this machine into your tailnet (a login link will appear):"
  sudo tailscale up --hostname="$TS_HOSTNAME"
fi
SERVER_NAME="$(sudo tailscale status --json | python3 -c 'import json,sys; print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))')"
[ -n "$SERVER_NAME" ] || die "Couldn't read this machine's Tailscale name."
ok "Tailscale name: $SERVER_NAME"
if [ -f .server_name ] && [ "$(cat .server_name)" != "$SERVER_NAME" ]; then
  die "This server was set up as $(cat .server_name), but Tailscale now calls it $SERVER_NAME. A Matrix server's name can't change; rename the machine back in Tailscale."
fi
echo "$SERVER_NAME" > .server_name

# ── 3. Settings & secrets ────────────────────────────────────────────────────
bold "3/7  Settings"
if [ ! -f .env ]; then
  MX_USER="$(ask "Your Matrix username (letters/numbers)" "$(whoami | tr -cd 'a-z0-9')")"
  PG_PASSWORD="$(openssl rand -hex 24)"
  umask 077
  cat > .env <<EOF
PG_PASSWORD=$PG_PASSWORD
MX_USER=$MX_USER
EOF
  umask 022
  ok "Saved settings to .env (private)"
fi
# shellcheck disable=SC1091
source .env
ok "You will be @$MX_USER:$SERVER_NAME"

mkdir -p postgres-init synapse bridges/imessage/data bridges/imessage/state
cat > postgres-init/01-databases.sql <<'EOF'
CREATE DATABASE imessage;
EOF

cat > compose.yml <<'EOF'
# Sculpin Server — generated by setup.sh
services:
  postgres:
    image: postgres:17
    restart: unless-stopped
    environment:
      POSTGRES_USER: sculpin
      POSTGRES_PASSWORD: ${PG_PASSWORD}
      POSTGRES_DB: synapse
      POSTGRES_INITDB_ARGS: "--encoding=UTF8 --lc-collate=C --lc-ctype=C"
    volumes:
      - ./postgres:/var/lib/postgresql/data
      - ./postgres-init:/docker-entrypoint-initdb.d:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U sculpin -d synapse"]
      interval: 5s
      retries: 20

  synapse:
    image: matrixdotorg/synapse:latest
    restart: unless-stopped
    depends_on:
      postgres:
        condition: service_healthy
    volumes:
      - ./synapse:/data
      - ./bridges/imessage/data/registration.yaml:/bridges/imessage-registration.yaml:ro
    ports:
      - "127.0.0.1:8008:8008"   # only this machine; Tailscale serves it to your devices

  imessage:
    image: ghcr.io/jasonlaguidice/imessage:latest
    restart: unless-stopped
    depends_on:
      - synapse
    environment:
      XDG_DATA_HOME: /state
    volumes:
      - ./bridges/imessage/data:/data
      - ./bridges/imessage/state:/state
EOF
ok "Wrote compose.yml"

# Small YAML helpers that keep comments intact (no extra packages needed).
cat > yamlset.py <<'PY'
import re, sys
def set_values(path, changes):
    lines = open(path).read().split("\n")
    stack = []
    done = set()
    for i, line in enumerate(lines):
        m = re.match(r'^(\s*)([A-Za-z0-9_]+):(\s*)(.*)$', line)
        if not m or line.lstrip().startswith("#"):
            continue
        indent = len(m.group(1))
        while stack and stack[-1][0] >= indent:
            stack.pop()
        stack.append((indent, m.group(2)))
        key = ".".join(k for _, k in stack)
        if key in changes:
            lines[i] = f"{m.group(1)}{m.group(2)}: {changes[key]}"
            done.add(key)
    open(path, "w").write("\n".join(lines))
    missing = set(changes) - done
    if missing:
        print("  ! not found in config (left as default):", ", ".join(sorted(missing)))
def replace_block(path, key_path, new_lines):
    """Replace the children of a mapping (e.g. bridge.permissions)."""
    lines = open(path).read().split("\n")
    stack = []
    for i, line in enumerate(lines):
        m = re.match(r'^(\s*)([A-Za-z0-9_]+):', line)
        if not m or line.lstrip().startswith("#"):
            continue
        indent = len(m.group(1))
        while stack and stack[-1][0] >= indent:
            stack.pop()
        stack.append((indent, m.group(2)))
        if ".".join(k for _, k in stack) != key_path:
            continue
        j = i + 1
        while j < len(lines):
            l = lines[j]
            if l.strip() and not l.lstrip().startswith("#") and len(l) - len(l.lstrip()) <= indent:
                break
            j += 1
        lines[i + 1:j] = [" " * (indent + 4) + l for l in new_lines]
        open(path, "w").write("\n".join(lines))
        return
    print("  ! block not found (left as default):", key_path)
PY

# ── 4. Synapse (Matrix server) ───────────────────────────────────────────────
bold "4/7  Matrix server (Synapse)"
sudo docker pull -q "$SYNAPSE_IMAGE" >/dev/null
sudo docker pull -q "$BRIDGE_IMAGE" >/dev/null
if [ ! -f synapse/homeserver.yaml ]; then
  sudo docker run --rm -v "$DIR/synapse:/data" \
    -e SYNAPSE_SERVER_NAME="$SERVER_NAME" -e SYNAPSE_REPORT_STATS=no \
    "$SYNAPSE_IMAGE" generate >/dev/null
  sudo python3 - "$DIR/synapse/homeserver.yaml" "$PG_PASSWORD" "$SERVER_NAME" <<'PY'
import re, sys
path, pw, server = sys.argv[1:4]
text = open(path).read()
text = re.sub(r'trusted_key_servers:\n(?:  .*\n)+', '', text)
text = re.sub(r'database:\n  name: sqlite3\n  args:\n    database: .*\n',
  "database:\n  name: psycopg2\n  args:\n    user: sculpin\n    password: %s\n    database: synapse\n    host: postgres\n    cp_min: 5\n    cp_max: 10\n" % pw, text)
text += f"""
# ── Sculpin: private, single-household server ──
public_baseurl: "https://{server}/"
serve_server_wellknown: true
enable_registration: false
# No federation: this server never talks to other Matrix servers.
federation_domain_whitelist: []
allow_public_rooms_over_federation: false
allow_public_rooms_without_auth: false
trusted_key_servers: []
suppress_key_server_warning: true
app_service_config_files:
  - /bridges/imessage-registration.yaml
"""
open(path, "w").write(text)
PY
  ok "Synapse configured (Postgres, no federation, registration closed)"
else
  ok "Synapse already configured"
fi

# ── 5. iMessage bridge config ────────────────────────────────────────────────
bold "5/7  iMessage bridge"
BCFG="$DIR/bridges/imessage/data/config.yaml"
BRUN="sudo docker run --rm -e XDG_DATA_HOME=/state -v $DIR/bridges/imessage/data:/data -v $DIR/bridges/imessage/state:/state $BRIDGE_IMAGE"
if [ ! -f "$BCFG" ]; then
  $BRUN -c /data/config.yaml -e >/dev/null 2>&1 || true
  [ -f "$BCFG" ] || die "The bridge didn't generate its config. Check: $BRUN -c /data/config.yaml -e"
  sudo chown "$(id -u):$(id -g)" "$BCFG"
  python3 - "$BCFG" "$SERVER_NAME" "$MX_USER" "$PG_PASSWORD" <<'PY'
import sys
sys.path.insert(0, ".")
from yamlset import set_values, replace_block
cfg, server, user, pw = sys.argv[1:5]
set_values(cfg, {
  "homeserver.address": "http://synapse:8008",
  "homeserver.domain": server,
  "appservice.address": "http://imessage:29332",
  "appservice.hostname": "0.0.0.0",
  "appservice.port": "29332",
  "database.type": "postgres",
  "database.uri": f"postgres://sculpin:{pw}@postgres/imessage?sslmode=disable",
  # Bridge <-> your apps: end-to-end encrypted, so the server's database only holds ciphertext
  "encryption.allow": "true",
  "encryption.default": "true",
  # The image ships ffmpeg + libheif: show iPhone photos/videos everywhere
  "network.video_transcoding": "true",
  "network.heic_conversion": "true",
})
replace_block(cfg, "bridge.permissions", [f'"{server}": user', f'"@{user}:{server}": admin'])
PY
  ok "Bridge configured"
fi
if [ ! -f bridges/imessage/data/registration.yaml ]; then
  $BRUN -c /data/config.yaml -g -r /data/registration.yaml >/dev/null 2>&1 || true
  [ -f bridges/imessage/data/registration.yaml ] || die "Couldn't generate the bridge registration."
  sudo chmod 644 bridges/imessage/data/registration.yaml
  sudo chmod 600 "$BCFG"   # holds the database password and bridge tokens
  ok "Bridge registered with the Matrix server"
fi

# ── 6. Start everything ──────────────────────────────────────────────────────
bold "6/7  Starting"
$DC up -d
for i in $(seq 1 60); do
  curl -fsS http://127.0.0.1:8008/health >/dev/null 2>&1 && break
  sleep 2
done
curl -fsS http://127.0.0.1:8008/health >/dev/null 2>&1 || die "Synapse didn't come up. Look at: $DC logs synapse"
ok "Matrix server is running"

if [ ! -f .user_created ]; then
  echo "  Create your Matrix account password now:"
  $DC exec synapse register_new_matrix_user -c /data/homeserver.yaml -a -u "$MX_USER" http://localhost:8008 </dev/tty
  touch .user_created
  ok "Account @$MX_USER:$SERVER_NAME created"
fi

# ── 7. Private HTTPS over Tailscale ──────────────────────────────────────────
bold "7/7  Private HTTPS (Tailscale)"
if sudo tailscale serve --bg --https=443 http://127.0.0.1:8008 >/dev/null 2>&1; then
  ok "Your devices can reach it at https://$SERVER_NAME"
else
  warn "tailscale serve failed — make sure HTTPS is enabled for your tailnet, then run:"
  warn "  sudo tailscale serve --bg --https=443 http://127.0.0.1:8008"
fi

# Helper command
sudo tee /usr/local/bin/sculpin-server >/dev/null <<EOF
#!/usr/bin/env bash
# Sculpin Server helper
DC="sudo docker compose -f $DIR/compose.yml --env-file $DIR/.env"
case "\${1:-}" in
  status)  \$DC ps ;;
  logs)    \$DC logs -f --tail=100 \${2:-} ;;
  restart) \$DC restart \${2:-} ;;
  update)  \$DC pull && \$DC up -d ;;
  imessage-login)
    echo "You'll need: your Apple ID + password, a 2FA code, and the hardware key from your Intel Mac."
    \$DC stop imessage
    \$DC run --rm -it imessage login -c /data/config.yaml
    \$DC up -d imessage ;;
  *) echo "Usage: sculpin-server {status|logs [service]|restart [service]|update|imessage-login}" ;;
esac
EOF
sudo chmod +x /usr/local/bin/sculpin-server

bold "Done!"
cat <<EOF
  Matrix server:  https://$SERVER_NAME   (only on your Tailscale network)
  Your account:   @$MX_USER:$SERVER_NAME

  Next:
   1. On a device on your tailnet, install Element (element.io) and sign in:
        homeserver https://$SERVER_NAME, user $MX_USER
   2. Connect iMessage (needs the hardware key from an Intel Mac and
      Contact Key Verification turned OFF on your Apple ID):
        sculpin-server imessage-login

  Handy:  sculpin-server status | logs imessage | restart | update
EOF
